#!/usr/bin/env bash
# Install the production settings from Vercel on the home server in one step.
#
#   npx vercel env pull --environment=production .env.prod     # on the Mac, once logged in
#   deploy/web/import-env.sh .env.prod --dry-run               # what would happen, no changes
#   deploy/web/import-env.sh .env.prod                         # do it
#   rm .env.prod                                               # the file holds every production secret
#
#   --new-credentials-secret   when neither the file nor the server has CREDENTIALS_SECRET (Vercel
#                              hides it as [SENSITIVE]), generate a new one on the server. Zotero keys
#                              sealed under the old one no longer open: whoever connected Zotero
#                              connects it again, once.
#
# What it does to /etc/dawmain/env on CT `web`:
#   - keeps the application's settings (Clerk, FILES_*, Zotero, CREDENTIALS_SECRET, e-Sbírka, …)
#   - drops what only made sense on Vercel (VERCEL_*, the Neon connection strings DATABASE_URL*,
#     PG*, POSTGRES_*, NEON_*, MIRROR_CF_ACCESS_* — the mirror is reached over the LAN) and
#     FILES_DATABASE_URL (Neon's app role)
#   - forces the home values: PUBLIC_URL, APP_ENV, APP_REGION, MIRROR_API_URL, and
#     FILES_DATABASE_URL from /root/files-db-urls.env on CT web — the HOME database `files`
#     (the data moves there at the switch, deploy/web/migrate-db.sh)
#   - drops MCP_BEARER_TOKEN: the shared access code is legacy and is NOT carried home (decided
#     16. 11. 2026) — the home endpoint accepts Clerk sign-in only
#   - backs up the old file (/etc/dawmain/env.bak-<time>, root only)
#   - rebuilds the live commit (FORCE=1 deploy.sh: NEXT_PUBLIC_* are inlined at build) and, if
#     that fails, puts the old file back.
# Never prints a value, only key names; FILES_DATABASE_URL and a generated CREDENTIALS_SECRET never
# leave the server. Run from a checkout of the repository on the Mac (needs `ssh pve`).
# See docs/infra/migrace-z-vercelu.md, phase 4.
set -euo pipefail

PVE="${PVE:-pve}"
INPUT=""
DRY=0
NEW_SECRET=0
for arg in "$@"; do
  case "$arg" in
    --dry-run) DRY=1 ;;
    --new-credentials-secret) NEW_SECRET=1 ;;
    -*) INPUT="" ; break ;;
    *) INPUT="$arg" ;;
  esac
done
[ -n "$INPUT" ] && [ -r "$INPUT" ] || { echo "usage: $0 <env file from vercel env pull> [--dry-run] [--new-credentials-secret]" >&2; exit 2; }
# LANG=C: the Mac's locale, forwarded by ssh, makes perl (pct) warn on every call.
export LC_ALL=C LANG=C

# Key NAMES that must not be carried over from Vercel (whole-name match).
DROP='^(VERCEL.*|NX_.*|TURBO_.*|DATABASE_URL.*|PG[A-Z]*|POSTGRES_.*|NEON_.*|MIRROR_CF_ACCESS_.*|MCP_BEARER_TOKEN|MCP_URL|FILES_DATABASE_URL|PUBLIC_URL|APP_ENV|APP_REGION|MIRROR_API_URL|DAWMAIN_REQUIRE_AUTH|TRUST_FORWARDED_HOST|NEXT_OUTPUT|NEXT_DEPLOYMENT_ID|GIT_SHA)$'
# FILES_DATABASE_URL is not here: it always comes from the server (checked below).
REQUIRED="NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY CLERK_SECRET_KEY FILES_MODE FILES_OPERATOR_IDS CREDENTIALS_SECRET"

TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT
chmod 600 "$TMP"

# KEY=VALUE lines only (comments and blanks are dropped), minus the dropped keys.
ALL="$(grep -E '^[A-Za-z_][A-Za-z0-9_]*=' "$INPUT" || true)"
# `vercel env pull` writes "[SENSITIVE]" for values Vercel never gives back: such a key is
# MISSING, not set — its value has to come from where it was created (see the dry run).
SENSITIVE="$(grep -E '^[A-Za-z_][A-Za-z0-9_]*=.*\[SENSITIVE\]' <<<"$ALL" | cut -d= -f1 | sort || true)"
ALL="$(grep -v '\[SENSITIVE\]' <<<"$ALL" || true)"
awk -F= -v re="$DROP" '$1 !~ re' <<<"$ALL" > "$TMP"
KEPT="$(cut -d= -f1 "$TMP" | sort)"
DROPPED="$(cut -d= -f1 <<<"$ALL" | sort | awk -v re="$DROP" '$0 ~ re')"

# Values that live on the home servers already: kept when the file has none.
#   CRON_SECRET, AI_GATEWAY_API_KEY, CREDENTIALS_SECRET  from the current
#                                    /etc/dawmain/env (CT web; a CREDENTIALS_SECRET generated by an
#                                    earlier --new-credentials-secret stays)
#   MIRROR_API_TOKEN                 from /etc/mirror/env (CT app, the mirror API itself)
from_server() {  # <ct> <file> <key>: the KEY=VALUE line, or nothing
  ssh -o BatchMode=yes "$PVE" "pct exec $1 -- sh -s" <<<"grep '^$3=' $2 | tail -1" 2>/dev/null || true
}
for spec in "103 /etc/dawmain/env CRON_SECRET" "103 /etc/dawmain/env NEXT_SERVER_ACTIONS_ENCRYPTION_KEY" "103 /etc/dawmain/env AI_GATEWAY_API_KEY" \
            "103 /etc/dawmain/env CREDENTIALS_SECRET" \
            "103 /etc/dawmain/env MIRROR_API_TOKEN" "102 /etc/mirror/env MIRROR_API_TOKEN"; do
  set -- $spec
  grep -q "^$3=" "$TMP" && continue
  LINE="$(from_server "$1" "$2" "$3")"
  [ -n "$LINE" ] && { echo "$LINE" >> "$TMP"; echo "$3: taken from the server (CT $1)."; }
done

# The home values, always last so they win.
cat >> "$TMP" <<'EOF'
PUBLIC_URL=https://dawmain.davidzavada.cz
APP_ENV=production
APP_REGION=home
MIRROR_API_URL=http://192.168.0.52:8080
EOF

echo "Kept from the file ($(wc -l <<<"$KEPT" | tr -d ' ')):";  sed 's/^/  /' <<<"$KEPT"
echo "Dropped (Vercel / Neon / home overrides):";              sed 's/^/  /' <<<"${DROPPED:-(none)}"
[ -n "$SENSITIVE" ] && { echo "Hidden by Vercel ([SENSITIVE], treated as missing):"; sed 's/^/  /' <<<"$SENSITIVE"; }
echo "Forced for the home server: PUBLIC_URL APP_ENV APP_REGION MIRROR_API_URL FILES_DATABASE_URL (home database)"
MISSING=""
if ! ssh -o BatchMode=yes "$PVE" "pct exec 103 -- sh -s" <<<"grep -q '^FILES_DATABASE_URL=.' /root/files-db-urls.env" 2>/dev/null; then
  MISSING=" FILES_DATABASE_URL(in /root/files-db-urls.env on CT web)"
fi
GEN_SECRET=0
if ! grep -q '^CREDENTIALS_SECRET=.' "$TMP"; then
  if [ "$NEW_SECRET" = 1 ]; then
    GEN_SECRET=1
    echo "CREDENTIALS_SECRET: none in the file or on the server — a NEW one will be generated on the server."
    echo "  Consequence: Zotero keys sealed under the old secret no longer open; every user who connected"
    echo "  Zotero has to connect it again, once (their Zotero data is not affected)."
  else
    MISSING="$MISSING CREDENTIALS_SECRET(or --new-credentials-secret)"
  fi
fi
for key in $REQUIRED; do
  [ "$key" = CREDENTIALS_SECRET ] && continue
  grep -q "^$key=" "$TMP" || MISSING="$MISSING $key"
done
if [ -n "$MISSING" ]; then
  echo "MISSING required keys:$MISSING" >&2
  echo "(Vercel hides 'sensitive' variables from env pull — add those by hand to $INPUT first.)" >&2
  [ "$DRY" = 1 ] || { echo "Nothing was changed." >&2; exit 1; }
fi
[ "$DRY" = 1 ] && { echo "Dry run: nothing was changed."; exit 0; }

STAMP="$(date +%Y%m%d-%H%M%S)"
echo "Installing /etc/dawmain/env (backup: env.bak-$STAMP) …"
ssh -o BatchMode=yes "$PVE" "pct exec 103 -- sh -c 'umask 077; cat > /etc/dawmain/env.new'" < "$TMP"
# Server-side additions (never through the Mac): the home database URL, and a new
# CREDENTIALS_SECRET when asked for. Then the installed key names, for the record.
ssh -o BatchMode=yes "$PVE" "pct exec 103 -- sh -s" <<EOF
set -e
umask 077
grep '^FILES_DATABASE_URL=' /root/files-db-urls.env | tail -1 >> /etc/dawmain/env.new
if [ "$GEN_SECRET" = 1 ]; then
  printf 'CREDENTIALS_SECRET=%s\n' "\$(head -c 32 /dev/urandom | base64)" >> /etc/dawmain/env.new
fi
cp -a /etc/dawmain/env /etc/dawmain/env.bak-$STAMP
chmod 600 /etc/dawmain/env.bak-$STAMP
chown root:dawmain /etc/dawmain/env.new
chmod 640 /etc/dawmain/env.new
mv /etc/dawmain/env.new /etc/dawmain/env
echo "Installed keys: \$(cut -d= -f1 /etc/dawmain/env | grep -v '^#' | sort | tr '\n' ' ')"
EOF

echo "Rebuilding the live commit with the new settings (a few minutes) …"
current() { ssh -o BatchMode=yes "$PVE" "pct exec 103 -- sh -s" <<<"readlink /opt/dawmain-web/current"; }
BEFORE_REL="$(current)"
LOG="$(mktemp)"
# `git pull`, not fetch: deploy.sh itself comes from the working tree of the server's clone.
if ssh -o BatchMode=yes "$PVE" "pct exec 103 -- sudo -u dawmain bash -c 'cd /opt/dawmain-web/repo && git checkout -q main && git pull -q origin main && FORCE=1 bash deploy/web/deploy.sh origin/main'" >"$LOG" 2>&1; then
  DEPLOY_OK=1
else
  DEPLOY_OK=0
fi
grep -E '^== |ERROR|passed|Live|Removed|rolled|already' "$LOG" || true
rm -f "$LOG"
AFTER_REL="$(current)"
# A deploy that exits 0 without switching (an old deploy.sh that says "already live") did NOT
# rebuild: the running service has not seen the new settings.
if [ "$DEPLOY_OK" = 1 ] && [ "$AFTER_REL" = "$BEFORE_REL" ]; then
  echo "deploy.sh finished but did not build a new release." >&2
  DEPLOY_OK=0
fi

if [ "$DEPLOY_OK" = 1 ]; then
  echo "Done: $(basename "$BEFORE_REL") → $(basename "$AFTER_REL"). Next: deploy/web/preflight.sh"
else
  echo "Failed — putting the old settings back (the service still runs $(basename "$AFTER_REL"))." >&2
  ssh -o BatchMode=yes "$PVE" "pct exec 103 -- sh -s" <<RESTORE
cp -a /etc/dawmain/env.bak-$STAMP /etc/dawmain/env && chown root:dawmain /etc/dawmain/env && chmod 640 /etc/dawmain/env
RESTORE
  exit 1
fi
